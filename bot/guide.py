def menu_keyboard() -> InlineKeyboardMarkup:
    rows = [[InlineKeyboardButton(label, callback_data=f"help:{key}")]
            for key, (label, _) in TOPICS.items()]
    return InlineKeyboardMarkup(rows)


def back_keyboard() -> InlineKeyboardMarkup:
    return InlineKeyboardMarkup(
        [[InlineKeyboardButton("⬅️ Назад к разделам", callback_data="help:menu")]]
    )


def get_topic(key: str) -> str:
    item = TOPICS.get(key)
    return item[1] if item else INTRO
